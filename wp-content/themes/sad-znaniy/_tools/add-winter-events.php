$existing = array();
foreach ( get_posts( array( "post_type" => "calendar_event", "post_status" => array( "publish", "draft", "pending", "future" ), "posts_per_page" => -1, "fields" => "ids" ) ) as $id ) {
	$existing[ get_the_title( $id ) . "|" . (string) get_post_meta( $id, "_sz_event_date_from", true ) ] = $id;
}

$created = 0; $skipped = 0;
foreach ( $events as $e ) {
	list( $work, $title, $from, $to, $regions, $diff, $pr, $text, $hint ) = $e;
	$key = $title . "|" . $from;
	if ( isset( $existing[ $key ] ) ) {
		echo "пропуск (есть #" . $existing[ $key ] . "): " . $title . "\n";
		$skipped++;
		continue;
	}
	if ( ! $confirm ) {
		echo "план: " . $from . "—" . $to . " | " . $work . " | " . $regions . " | " . $title . "\n";
		continue;
	}
	$id = wp_insert_post( array( "post_type" => "calendar_event", "post_status" => "draft", "post_title" => $title, "post_content" => $text ) );
	if ( ! $id || is_wp_error( $id ) ) {
		echo "ОШИБКА: " . $title . "\n";
		continue;
	}
	update_post_meta( $id, "_sz_event_date_from", $from );
	update_post_meta( $id, "_sz_event_date_to", $to );
	update_post_meta( $id, "_sz_event_regions", ( "all" === $regions ? "" : $regions ) );
	update_post_meta( $id, "_sz_event_all_regions", ( "all" === $regions ? "1" : "" ) );
	update_post_meta( $id, "_sz_event_crop", 0 );
	update_post_meta( $id, "_sz_event_difficulty", $diff );
	update_post_meta( $id, "_sz_event_priority", $pr );
	update_post_meta( $id, "_sz_event_weather_hint", $hint );
	update_post_meta( $id, "_sz_event_recurring", "1" );
	wp_set_object_terms( $id, $work, "work_type" );
	echo "создано #" . $id . ": " . $title . "\n";
	$created++;
}

echo "---\nитого: создано " . $created . ", пропущено " . $skipped . " (режим: " . ( $confirm ? "confirm" : "dry" ) . ")\n";
if ( $confirm && $created ) {
	sad_znaniy_programmatic_matrix();
	sad_znaniy_seo_recalc();
	echo "матрица пересобрана, привязки пересчитаны\n";
}
