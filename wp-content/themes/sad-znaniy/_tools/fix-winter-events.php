<?php

// Только CLI: скрипты разработки не исполняются из браузера (Этап 7.3, S2).
if ( 'cli' !== PHP_SAPI ) {
	http_response_code( 403 );
	header( 'Content-Type: text/plain; charset=utf-8' );
	exit( 'Скрипт запускается только из командной строки.' );
}
/**
 * ПРАВКИ ЗИМНИХ ЧЕРНОВИКОВ (#758–#772) по вычитке владельца (14.10.2026).
 *
 * Принято 12 без правок, правки — в 6: #758 (даты + повторяемость),
 * #759 (даты + ледяной дождь), #762 и #766 (разведены акценты: запасы
 * против сроков), #764 (закупки вместо «лунных дней»), #768 (гладиолусы
 * и георгины). Сложность: опытный — только #763 (прививка) и #769 (обрезка),
 * остальные — новичок.
 *
 * Публикацию скрипт НЕ выполняет: черновики остаются черновиками,
 * публикует владелец массовым действием в админке.
 *
 * Запуск: php.exe _tools/fix-winter-events.php dry|confirm
 *
 * @package sad-znaniy
 */

if ( ! defined( "ABSPATH" ) ) {
	require dirname( __DIR__, 4 ) . "/wp-load.php";
}

$args    = isset( $argv ) ? array_slice( $argv, 1 ) : array();
$confirm = in_array( "confirm", $args, true );

// id => [ заголовок|null, дата с, дата по, сложность, подсказка, текст|null ].
$fix = array(
	758 => array( null, "2026-12-01", "2027-02-28", "new", "Повторять после каждого сильного снегопада", "Снег с дорожек и открытых мест перебрасывают на грядки и в приствольные круги слоем 20–30 см: под ним почва промерзает заметно меньше, а весной грядки дольше держат влагу. Уплотнять снег не нужно — рыхлый слой греет лучше. Работа повторяющаяся: после каждого сильного снегопада набрасывать снег на грядки и в приствольные круги." ),
	759 => array( null, "2026-12-01", "2027-02-28", "new", "Лёд не тянуть: ждать оттепели", "После каждого мокрого снегопада и ледяного дождя снег стряхивают вверх по ветвям, а не вниз: иначе ветви ломаются под весом. В феврале ледяной дождь особенно опасен для хвойных — ветви под коркой не вытягивают силой, а ждут оттепели. Связанные хвойные (туя, можжевельник) дополнительно обвязывают шпагатом, чтобы крона не разваливалась." ),
	762 => array( "Ревизия семян: что есть и что докупить", null, null, "new", "Список «что докупить» — сразу, по культурам", "Перебирают оставшиеся пакеты: проверяют сроки годности, отбраковывают вздутые и подмокшие. Тут же составляют список того, чего не хватает, — по культурам и сортам, с количеством; так к посевной не окажется, что редкий сорт распродан. Условия хранения: +10…+15 °C, влажность ниже 60 %, семена в бумажных пакетах." ),
	764 => array( "Планирование закупок: семена и грунт к сезону", null, null, "new", "Список покупок — до конца декабря", "Популярные сорта раскупают к февралю — составьте список до конца декабря. Грунт берут свежий, не с огорода, и промораживают на балконе 5–7 дней: это снижает запас вредителей и семян сорняков. Расчёт простой: 10–15 л на 100 корней рассады." ),
	766 => array( "Планирование сроков посевов по лунному календарю", null, null, "new", "По неделям; луна — про сроки", "План пишут по неделям, а не по числам: главный ориентир — погода, лунный календарь подсказывает удачные дни для посева и подкормок. Заранее отметьте дни обработок и подкормок, чтобы не смешивать их с посевом." ),
	768 => array( "Гладиолусы и георгины на хранении: перебрать и досушить", null, null, "new", "Гниль — до здоровой ткани и досушить", "Клубнелуковицы гладиолусов и корнеклубни георгинов перебирают: удаляют мягкие, с гнилью и пятнами, повреждённое место подрезают до здоровой ткани и подсушивают срез. Хранят в один-два слоя, в бумаге или опилках, при +3…+7 °C и влажности 60–70 %: в тепле и сырости клубни трогаются в рост и загнивают." ),
	760 => array( null, null, null, "new", null, null ),
	770 => array( null, null, null, "new", null, null ),
);

$ids = range( 758, 772 );
if ( $confirm ) {
	echo "=== ПРИМЕНЯЮ ПРАВКИ ===\n";
}

foreach ( $ids as $id ) {
	$p = get_post( $id );
	if ( ! $p || "calendar_event" !== $p->post_type ) {
		echo "нет записи #" . $id . "\n";
		continue;
	}
	$before = get_post_meta( $id, "_sz_event_difficulty", true );
	if ( isset( $fix[ $id ] ) ) {
		list( $title, $from, $to, $diff, $hint, $text ) = $fix[ $id ];

		if ( $confirm ) {
			$post = array( "ID" => $id );
			if ( $title ) {
				$post["post_title"] = $title;
			}
			if ( $text ) {
				$post["post_content"] = $text;
			}
			wp_update_post( $post );
			if ( $from ) {
				update_post_meta( $id, "_sz_event_date_from", $from );
			}
			if ( $to ) {
				update_post_meta( $id, "_sz_event_date_to", $to );
			}
			if ( $hint ) {
				update_post_meta( $id, "_sz_event_weather_hint", $hint );
			}
			if ( $diff !== $before ) {
				update_post_meta( $id, "_sz_event_difficulty", $diff );
			}
			echo "правлено #" . $id . " | сложность: " . $before . " → " . $diff . "\n";
		} else {
			echo "план #" . $id . ": сложность " . $before . " → " . $diff
				. " | даты " . ( $from ? $from : get_post_meta( $id, "_sz_event_date_from", true ) )
				. "—" . ( $to ? $to : get_post_meta( $id, "_sz_event_date_to", true ) )
				. ( $title ? " | новое имя: " . $title : "" ) . "\n";
			continue;
		}
	}
	echo "  #" . $id . " " . get_the_title( $id ) . " | "
		. get_post_meta( $id, "_sz_event_date_from", true ) . "—" . get_post_meta( $id, "_sz_event_date_to", true )
		. " | сложность: " . get_post_meta( $id, "_sz_event_difficulty", true )
		. " | приоритет: " . get_post_meta( $id, "_sz_event_priority", true ) . "\n";
}

echo "---\nрежим: " . ( $confirm ? "confirm (правки применены, публикация НЕ выполнена)" : "dry" ) . "\n";
