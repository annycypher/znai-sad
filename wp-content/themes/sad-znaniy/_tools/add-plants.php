$sz_created = 0;
$sz_updated = 0;

foreach ( $sz_plants as $sz_pl ) {
	$content  = sz_b_p( $sz_pl['intro'] );
	$content .= "\n" . sz_b_img( $sz_pl['alt'] );
	$content .= sz_b_h2( 'Посадка' ) . "\n" . sz_b_p( $sz_pl['planting'] );
	$content .= sz_b_h2( 'Уход' ) . "\n" . sz_b_ol( $sz_pl['care'] );
	$content .= sz_b_h2( 'Болезни и вредители' ) . "\n" . sz_b_p( $sz_pl['pests'] );
	$content .= sz_b_h2( 'Частые ошибки' ) . "\n" . sz_b_ul( $sz_pl['mistakes'] );
	$content .= sz_b_h2( 'Частые вопросы' ) . "\n";
	foreach ( $sz_pl['faq'] as $sz_q ) {
		$content .= sz_b_h3( $sz_q[0] ) . "\n" . sz_b_p( $sz_q[1] ) . "\n";
	}
	$content .= sz_b_h2( 'Что почитать дальше' ) . "\n" . sz_b_links( $sz_pl['links'] );

	$args     = array(
		'post_type'    => 'plant',
		'post_status'  => 'publish',
		'post_title'   => $sz_pl['title'],
		'post_name'    => $sz_pl['slug'],
		'post_content' => $content,
	);
	$existing = get_page_by_path( $sz_pl['slug'], OBJECT, 'plant' );

	if ( $existing ) {
		$args['ID'] = (int) $existing->ID;
		$pid        = wp_update_post( $args );
		$sz_updated++;
	} else {
		$pid = wp_insert_post( $args );
		$sz_created++;
	}

	if ( is_wp_error( $pid ) || ! $pid ) {
		echo 'ОШИБКА: ' . $sz_pl['title'] . "\n";
		continue;
	}

	update_post_meta( $pid, '_sz_plant_light', $sz_pl['light'] );
	update_post_meta( $pid, '_sz_plant_water', $sz_pl['water'] );
	update_post_meta( $pid, '_sz_plant_ph_from', $sz_pl['ph'][0] );
	update_post_meta( $pid, '_sz_plant_ph_to', $sz_pl['ph'][1] );
	update_post_meta( $pid, '_sz_plant_soil', $sz_pl['soil'] );
	update_post_meta( $pid, '_sz_plant_neighbors_good', $sz_pl['good'] );
	update_post_meta( $pid, '_sz_plant_neighbors_bad', $sz_pl['bad'] );
	update_post_meta( $pid, '_sz_plant_lunar_cat', $sz_pl['lunar'] );
	update_post_meta( $pid, '_sz_seo_title', $sz_pl['seo_title'] );
	update_post_meta( $pid, '_sz_seo_description', $sz_pl['seo_desc'] );

	wp_set_object_terms( $pid, $sz_pl['section'], 'plant_section' );
	wp_set_object_terms( $pid, $sz_pl['type'], 'plant_type' );

	echo 'OK #' . $pid . ' | ' . str_pad( $sz_pl['title'], 12 ) . ' | SEO: ' . mb_strlen( $sz_pl['seo_title'] ) . ' зн. / ' . mb_strlen( $sz_pl['seo_desc'] ) . " зн. | " . home_url( '/rasteniya/' . $sz_pl['slug'] . '/' ) . "\n";
}

echo "\nсоздано: {$sz_created}, обновлено: {$sz_updated}\n";






