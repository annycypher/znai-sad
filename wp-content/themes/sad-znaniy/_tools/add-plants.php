/** Абзац. */
function sz_b_p( $t ) {
	return '<!-- wp:paragraph --><p>' . $t . '</p><!-- /wp:paragraph -->';
}
/** Заголовок h2. */
function sz_b_h2( $t ) {
	return "\n<!-- wp:heading --><h2>" . $t . "</h2><!-- /wp:heading -->";
}
/** Заголовок h3. */
function sz_b_h3( $t ) {
	return '<!-- wp:heading {"level":3} --><h3>' . $t . '</h3><!-- /wp:heading -->';
}
/** Изображение-заглушка с alt. */
function sz_b_img( $alt ) {
	return '<!-- wp:image --><figure class="wp-block-image"><img alt="' . $alt . '" /><!-- TODO: фото --></figure><!-- /wp:image -->';
}
/** Нумерованный список. */
function sz_b_ol( $items ) {
	$li = '';
	foreach ( $items as $i ) {
		$li .= '<li>' . $i . '</li>';
	}
	return '<!-- wp:list {"ordered":true} --><ol>' . $li . '</ol><!-- /wp:list -->';
}
/** Маркированный список. */
function sz_b_ul( $items ) {
	$li = '';
	foreach ( $items as $i ) {
		$li .= '<li>' . $i . '</li>';
	}
	return '<!-- wp:list --><ul>' . $li . '</ul><!-- /wp:list -->';
}
/** Список внутренних ссылок. */
function sz_b_links( $items ) {
	$li = '';
	foreach ( $items as $i ) {
		$li .= '<li><a href="' . $i[1] . '">' . $i[0] . '</a></li>';
	}
	return '<!-- wp:list --><ul>' . $li . '</ul><!-- /wp:list -->';
}

